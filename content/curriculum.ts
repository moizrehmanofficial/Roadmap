/**
 * The full DevGuide curriculum.
 *
 * Tracks → Modules → Lessons.
 * A lesson is "published" when a matching MDX file exists at
 *   content/lessons/<track>/<module>/<lesson-slug>.mdx
 * Otherwise it shows up on the site as "planned", so the whole roadmap
 * is visible from day one.
 *
 * Lesson slugs are derived from titles with `slugify()` (lib/slug.ts),
 * unless written as [title, slug].
 */

export type LessonEntry = string | [title: string, slug: string];

export interface ModuleDef {
  slug: string;
  title: string;
  summary: string;
  lessons: LessonEntry[];
}

